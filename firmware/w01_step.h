static enum W01Kind w01_kind(UINT8 *vmcb, UINT32 pc, const UINT64 gpr[14])
{
    if (pc<0xfffff000u) return W01Reject;
    UINT16 cs=FIELD(UINT16,Cs), attr=FIELD(UINT16,Cs+2);
    UINT64 base=FIELD(UINT64,Cs+8), ax=FIELD(UINT64,Rax), cr0=FIELD(UINT64,Cr0);
    UINT8 mode=0;
    if (cs==0xf000 && base==0xffff0000u && !(attr&0x600) && !(cr0&(1ull<<31))) mode=16;
    if (cs==0x10 && !base && (attr&0x600)==0x400 && (cr0&1)) mode=32;
    if (cs==0x38 && !base && (attr&0x600)==0x200 && (FIELD(UINT64,GuestEfer)&0x400)) mode=64;
    if (!mode || w01_page(vmcb,Code)[pc&0xfff]!=mode) return W01Reject;
    switch (pc&0xfff) {
    case 0xe79: if ((UINT16)gpr[0]!=0xfea8) return W01Reject; break; /* lgdt cs:[bx] */
    case 0xe87: case 0x6f1: /* far JMP through the real, RO VTF GDT; no task gates */
        if (FIELD(UINT64,0x468)!=0xfffffeb0u || FIELD(UINT32,0x464)!=0x3f ||
            !w01_identity(vmcb,0xfffffeb0u) || !(cr0&1)) return W01Reject;
        break;
    case 0xe84: if (ax!=0x23) return W01Reject; break;
    case 0xe94: if (ax!=0x640) return W01Reject; break;
    case 0x69c: if (ax!=0x660) return W01Reject; break;
    case 0x930: if (ax!=W01RamGpa) return W01Reject; break;
    case 0x6e9: if (ax!=0x80000033u) return W01Reject; break;
    case 0x93d: case 0xb7f: return W01Cpuid;
    case 0x6af: return W01ReadEfer;
    case 0x6b5: return W01WriteEfer;
    case 0xf37: return gpr[4]==W01_SEC_GPA ? W01JumpSec : W01Reject; /* jmp rsi */
    }
    return W01Scalar;
}
