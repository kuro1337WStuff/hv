/* Hand-reviewed starts in the actual edk2-stable202611 RELEASE/GCC VTF
 * page. These are page offsets, not guest-configurable entry points. A
 * rebuild cannot use this table unless the complete page still matches.
 * No decoding or emulation of the listed arithmetic/branches: hardware
 * executes them with TF and #DB interception; no strings, stack flags,
 * debug register access, SIMD, hidden VM transitions, or interrupt handlers.
 * MOV SS at ea3 has exactly one following direct JMP (ea5) in its shadow.
 * Failure/hang, AP, SEV/TDX, and padding/data paths are not admitted. */
