#ifndef HV_LINUX_INPUT_GATE_H
#define HV_LINUX_INPUT_GATE_H

#include "hv_sha256.h"

enum LinuxInput { LinuxInputOK=0, LinuxInputKernel=1, LinuxInputInitrd=2, LinuxInputCmdline=3 };

static enum LinuxInput linux_bad_input(const UINT8 *media)
{
    /* Compiled trust anchors, never loaded from the staged filesystem. */
    static const struct {
        enum LinuxInput id;
        size_t offset, length;
        uint8_t pin[32];
    } inputs[] = {
        {LinuxInputKernel, LinuxImageOff, LinuxImageLen,
         {0x1e,0x8a,0xc7,0xae,0xbf,0xab,0x3f,0x0f,0xcb,0x44,0x3e,0xae,0x94,0xad,0x32,0x0e,
          0xfb,0xbd,0xa5,0x1b,0xe9,0x1b,0x92,0x8c,0x32,0xca,0x17,0x40,0xb4,0x4e,0xbe,0x9d}},
        {LinuxInputInitrd, LinuxRdOff, LinuxRdLen,
         {0x99,0xdb,0x7e,0x0b,0xb0,0x74,0x26,0x19,0xd8,0x5d,0xea,0xab,0x03,0x1f,0xf7,0xa5,
          0x39,0xcd,0x8e,0x46,0xcb,0x6b,0x7d,0xd8,0xed,0x8d,0xd0,0x11,0x96,0xe3,0xba,0xa4}},
        {LinuxInputCmdline, LinuxCmdOff, LinuxCmdLen,
         {0x51,0x61,0xea,0xc9,0xcd,0x95,0x35,0x3e,0x2d,0x47,0x91,0x7e,0x60,0xe4,0x6b,0xef,
          0x06,0x30,0xb6,0x4f,0x4b,0xc2,0x64,0x5f,0x4c,0xff,0xd2,0xb1,0x7f,0x1b,0xf9,0x58}}
    };
    uint8_t digest[32];
    for (size_t i=0; i<sizeof(inputs)/sizeof(inputs[0]); ++i) {
        unsigned diff=0;
        hv_sha256(media+inputs[i].offset, inputs[i].length, digest);
        for (size_t j=0; j<sizeof(digest); ++j) diff |= digest[j]^inputs[i].pin[j];
        if (diff) return inputs[i].id;
    }
    return LinuxInputOK;
}

#endif
